// Builds the LG webOS package:
//   src/  ──esbuild(bundle, iife)──►  ──Babel(preset-env, chrome 38)──►  ES5 app.js (+ inline ES5 Web Worker)
//   ──►  build-webos/  ──ares-package──►  release/com.example.iptvplayer_1.0.0_all.ipk
// Finally embeds the .ipk + companion server into src/generated/downloads.ts so the
// single-file web build (vite) can offer both as downloads.
//
//   node scripts/build-webos.mjs
import esbuild from "esbuild";
import * as babel from "@babel/core";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const root = process.cwd();
const OUT = path.join(root, "build-webos");
const RELEASE = path.join(root, "release");
const DOWNLOADS = path.join(root, "src/generated/downloads.ts");
const t0 = Date.now();
const log = (m) => console.log("[webos] " + m);

const define = { "process.env.NODE_ENV": '"production"' };

async function toES5(code) {
  const r = await babel.transformAsync(code, {
    configFile: path.join(root, "babel.config.js"),
    sourceType: "script",
    compact: true,
    comments: false,
    filename: "bundle.js",
  });
  return r.code;
}

function assertES5(name, code) {
  let acorn;
  try {
    acorn = require("acorn");
  } catch (e) {
    log("acorn not installed, skipping ES5 syntax verification of " + name);
    return;
  }
  try {
    acorn.parse(code, { ecmaVersion: 5, sourceType: "script" });
    log("✓ " + name + " is valid ES5 (" + Math.round(code.length / 1024) + " KB)");
  } catch (e) {
    const at = e.pos || 0;
    throw new Error("ES5 check failed for " + name + ": " + e.message + "\n..." + code.substring(at - 80, at + 80));
  }
}

// `import W from "./x.worker?worker&inline"` -> ES5 Blob worker (same contract as Vite's inline workers).
const workerPlugin = {
  name: "inline-worker",
  setup(build) {
    build.onResolve({ filter: /\?worker&inline$/ }, (a) => ({
      path: path.resolve(a.resolveDir, a.path.replace("?worker&inline", ".ts")),
      namespace: "inline-worker",
    }));
    build.onLoad({ filter: /.*/, namespace: "inline-worker" }, async (a) => {
      const r = await esbuild.build({
        entryPoints: [a.path], bundle: true, write: false, format: "iife", target: "es2020",
        minify: true, define, logLevel: "warning", legalComments: "none",
      });
      const code = await toES5(r.outputFiles[0].text);
      assertES5("parser worker", code);
      return {
        loader: "js",
        contents:
          "export default function InlineWorker(){var b=new Blob([" + JSON.stringify(code) +
          '],{type:"text/javascript"});return new Worker((window.URL||window.webkitURL).createObjectURL(b));}',
      };
    });
  },
};

async function main() {
  // 0. start from a stub so the TV build never embeds an older .ipk
  fs.mkdirSync(path.dirname(DOWNLOADS), { recursive: true });
  fs.writeFileSync(
    DOWNLOADS,
    '// AUTO-GENERATED by scripts/build-webos.mjs (stub)\nexport const IPK_NAME = "";\nexport const IPK_BASE64 = "";\nexport const SERVER_NAME = "companion-server.mjs";\nexport const SERVER_SOURCE = "";\n'
  );
  if (!fs.existsSync(path.join(root, "public/icon.png"))) {
    execFileSync(process.execPath, [path.join(root, "scripts/make-icons.mjs")], { stdio: "inherit" });
  }

  // 1. bundle
  log("bundling with esbuild…");
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  const tmp = path.join(OUT, ".tmp");
  await esbuild.build({
    entryPoints: [path.join(root, "src/main.tsx")],
    bundle: true, format: "iife", target: "es2020", minify: true, define,
    outdir: tmp, entryNames: "app", plugins: [workerPlugin], logLevel: "warning", legalComments: "none",
    loader: { ".png": "dataurl", ".svg": "dataurl" },
  });

  // 2. ES5
  log("transpiling to ES5 (Chrome 38) with Babel — this takes a while…");
  const js = await toES5(fs.readFileSync(path.join(tmp, "app.js"), "utf8"));
  assertES5("app.js", js);
  fs.writeFileSync(path.join(OUT, "app.js"), js);

  const css = fs.readFileSync(path.join(tmp, "app.css"), "utf8");
  const bad = css.match(/display:\s*grid|grid-template|var\(--|[^-\w]gap:|:is\(|:has\(/g);
  if (bad) throw new Error("Chrome 38 incompatible CSS found: " + bad.join(", "));
  fs.writeFileSync(path.join(OUT, "app.css"), css);
  fs.rmSync(tmp, { recursive: true, force: true });
  log("✓ CSS has no grid / custom properties / gap / :is / :has");

  // 3. static files
  const pub = path.join(root, "public");
  for (const f of ["appinfo.json", "icon.png", "largeIcon.png", "webOSTV.js", "webOSTV.LICENSE.txt"]) {
    fs.copyFileSync(path.join(pub, f), path.join(OUT, f));
  }
  fs.writeFileSync(
    path.join(OUT, "index.html"),
    '<!DOCTYPE html>\n<html lang="en"><head><meta charset="utf-8">' +
      '<meta name="viewport" content="width=1920, initial-scale=1">' +
      "<title>StreamPlayer</title>" +
      '<link rel="stylesheet" href="app.css"></head>' +
      '<body><div id="root"></div>' +
      '<script src="webOSTV.js"></script><script src="app.js"></script></body></html>\n'
  );

  // 4. package .ipk
  log("packaging .ipk with ares-package…");
  fs.rmSync(RELEASE, { recursive: true, force: true });
  fs.mkdirSync(RELEASE, { recursive: true });
  execFileSync(path.join(root, "node_modules/.bin/ares-package"), ["--no-minify", "-o", RELEASE, OUT], { stdio: "inherit" });
  const ipk = fs.readdirSync(RELEASE).filter((f) => f.endsWith(".ipk"))[0];
  if (!ipk) throw new Error("ares-package did not produce an .ipk");
  fs.copyFileSync(path.join(root, "server/companion-server.mjs"), path.join(RELEASE, "companion-server.mjs"));
  log("✓ release/" + ipk + " (" + Math.round(fs.statSync(path.join(RELEASE, ipk)).size / 1024) + " KB)");

  // 5. embed downloads into the web build
  const b64 = fs.readFileSync(path.join(RELEASE, ipk)).toString("base64");
  const serverSrc = fs.readFileSync(path.join(root, "server/companion-server.mjs"), "utf8");
  fs.writeFileSync(
    DOWNLOADS,
    "// AUTO-GENERATED by scripts/build-webos.mjs — do not edit\n" +
      "export const IPK_NAME = " + JSON.stringify(ipk) + ";\n" +
      "export const IPK_BASE64 = " + JSON.stringify(b64) + ";\n" +
      'export const SERVER_NAME = "companion-server.mjs";\n' +
      "export const SERVER_SOURCE = " + JSON.stringify(serverSrc) + ";\n"
  );
  log("✓ embedded downloads into src/generated/downloads.ts");
  log("done in " + Math.round((Date.now() - t0) / 1000) + "s");
}

main().catch((e) => {
  console.error("[webos] FAILED:", e.message || e);
  process.exit(1);
});
